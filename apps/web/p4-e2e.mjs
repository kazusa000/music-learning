// Real service, real provider submission and durable citations. No stubbed responses.
import {chromium} from 'playwright';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const [tokenFile,projectId,output]=process.argv.slice(2);
if(!output||output.startsWith('\\\\'))throw new Error('New local output required');
await mkdir(output,{recursive:false});
const token=(await readFile(tokenFile,'ascii')).trim();
const browser=await chromium.launch({headless:true});
const errors=[];
try{
 const page=await browser.newPage({viewport:{width:1600,height:1120}});
 page.on('pageerror',error=>errors.push(String(error)));
 await page.goto(`http://127.0.0.1:8765/?project=${projectId}&view=workbench#token=${token}`);
 const studio=page.getByRole('region',{name:'音乐工作台'});await studio.waitFor();
 const api=async(operation,args={})=>{const r=await page.request.post('http://127.0.0.1:8765/v1/commands',{data:{operation,arguments:args}});const d=await r.json();assert.ok(d.ok,JSON.stringify(d));return d.result;};
 const revision=await api('revisions.get',{project_id:projectId});
 const before=await api('dialogue.list',{project_id:projectId,limit:1000});
 assert.ok(before.filter(t=>t.status==='succeeded').length>=2);
 await page.getByLabel('循环起点秒',{exact:true}).fill('60');await page.getByLabel('循环终点秒',{exact:true}).fill('90');
 const bassIndex=revision.snapshot.tracks.findIndex(t=>t.role==='bass'||t.instrument_candidates?.includes('GM:33'));
 assert.ok(bassIndex>=0);await page.locator('.track-select').nth(bassIndex).click();
 await page.getByLabel('上下文与设置',{exact:true}).click();await page.getByLabel('讨论上下文',{exact:true}).selectOption('selection');
 await page.getByLabel('Codex 登录方式',{exact:true}).selectOption('existing');
 const rate=revision.snapshot.sample_rate;
 await page.getByLabel('讨论问题',{exact:true}).fill(`请只调用 compare 比较这个贝斯声部的60–75秒与75–90秒：start_sample=${60*rate}，end_sample=${75*rate}，compare_start_sample=${75*rate}，compare_end_sample=${90*rate}。解释两个区间的音符密度和音域差异，并说明这些统计不能直接等价为声音张力。引用两处真实工程位置，200字以内。`);
 await page.getByRole('button',{name:'发送',exact:true}).click();
 await page.waitForFunction(count=>document.querySelectorAll('.discussion-turn').length>count,before.length);
 const id=await page.locator('.discussion-turn').last().getAttribute('data-turn');
 const article=page.locator(`[data-turn="${id}"]`);
 await page.waitForFunction(id=>['succeeded','failed','cancelled'].includes(document.querySelector(`[data-turn="${id}"]`)?.dataset.status),id,{timeout:240000});
 const turn=await api('dialogue.get',{project_id:projectId,turn_id:id});
 await writeFile(path.join(output,'turn.json'),JSON.stringify(turn,null,2));
 assert.equal(turn.status,'succeeded',JSON.stringify(turn.error));
 assert.equal(turn.payload.start_sample,60*rate);assert.equal(turn.payload.end_sample,90*rate);
 assert.equal(turn.payload.track_id,revision.snapshot.tracks[bassIndex].id);
 assert.ok(turn.tools.some(t=>t.arguments.action==='compare'));assert.ok(turn.citations.length>=2);
 await article.locator('.citation-list button').first().click();
 await page.waitForFunction(sample=>Math.abs(Number(document.querySelector('.studio')?.dataset.position)-sample)<.001,turn.citations[0].start_sample/rate);
 assert.equal(await studio.getAttribute('data-revision'),turn.revision_id);
 await article.getByRole('button',{name:'保存为研究笔记'}).click();
 await page.locator('.discussion-note').filter({hasText:turn.text.slice(0,12)}).waitFor();
 const notes=await api('conversations.list',{project_id:projectId,limit:1000});
 const note=notes.find(n=>n.context?.source_turn_id===id);
 assert.ok(note);assert.equal(note.revision_id,turn.revision_id);
 await page.reload();await studio.waitFor();
 await page.getByRole('button',{name:/^笔记 /}).click();await page.locator('.discussion-note').waitFor();
 await page.getByRole('button',{name:/^讨论 /}).click();
 await page.getByRole('img',{name:'整曲波形与钢琴卷帘'}).waitFor();
 await page.waitForFunction(()=>Number(document.querySelector('.piano-roll')?.dataset.waveformBuckets)>0);
 await page.screenshot({path:path.join(output,'workbench.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth);
 assert.ok(overflow<=1,String(overflow));assert.deepEqual(errors,[]);
 await writeFile(path.join(output,'summary.json'),JSON.stringify({status:'succeeded',turn_id:id,notes_saved:true,citation_position:true,reload:true,overflow,page_errors:errors},null,2));
 console.log(JSON.stringify({status:'succeeded',turn_id:id,overflow}));
}finally{await browser.close();}
