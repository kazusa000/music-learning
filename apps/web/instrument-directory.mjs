import {sandboxAudition} from './audition-sandbox.mjs';
const base='http://127.0.0.1:8765';
// Real local API and UI, no provider calls or musical edits.
import {chromium} from 'playwright';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const [tokenFile,projectId,output]=process.argv.slice(2);
await mkdir(output,{recursive:false});
const token=(await readFile(tokenFile,'ascii')).trim();
const browser=await chromium.launch({headless:true}),errors=[],productionWrites=[];
try{
  const page=await browser.newPage({viewport:{width:1600,height:1120}});
  page.on('pageerror',e=>errors.push(String(e)));
  page.on('request',request=>{if(!request.url().endsWith('/v1/commands'))return;
    const body=request.postDataJSON();if(['dialogue.submit','jobs.submit','edits.apply','arrangements.apply'].includes(body.operation))productionWrites.push(body.operation);});
  await sandboxAudition(page,base,token);await page.goto(`http://127.0.0.1:8765/?project=${projectId}&view=workbench#token=${token}`);
  await page.getByRole('region',{name:'音乐工作台'}).waitFor();
  assert.deepEqual(await page.getByRole('tablist',{name:'侧栏内容'}).getByRole('tab').allTextContents(),['讨论','音色与效果','版本','分析']);
  await page.getByRole('tab',{name:'讨论',exact:true}).focus();await page.keyboard.press('End');
  assert.equal(await page.getByRole('tab',{name:'分析',exact:true}).getAttribute('aria-selected'),'true');
  await page.getByRole('tab',{name:'音色与效果',exact:true}).click();
  const choose=page.getByRole('button',{name:'让 AI 选音色 ↗',exact:true});
  await page.locator('[data-preset-id="salamander-grand"]').waitFor();
  assert.ok(await choose.isDisabled());
  await page.locator('.track-select').first().click();
  assert.ok(await choose.isEnabled());
  const soundTrack=page.getByLabel('音色与效果的音轨',{exact:true});
  const trackOptions=await soundTrack.locator('option').evaluateAll(nodes=>nodes.map(n=>n.value));
  assert.equal(await soundTrack.inputValue(),trackOptions[1]);
  await soundTrack.selectOption(trackOptions[2]);
  assert.ok(await page.locator('.track-card').nth(1).evaluate(node=>node.classList.contains('is-selected')));
  await page.locator('.sound-slot').first().waitFor();
  const slotId=await page.locator('.sound-slot').first().getAttribute('data-plugin-id');
  await page.locator('.sound-slot summary').first().click();
  assert.ok(await page.locator('.sound-slot .parameter-list').first().isVisible());
  await soundTrack.selectOption(trackOptions[1]);
  assert.notEqual(await page.locator('.sound-slot').first().getAttribute('data-plugin-id'),slotId);
  await page.getByLabel('选择乐器',{exact:true}).selectOption('electric-guitar');
  await page.locator('[data-preset-id="shiny-electric"]').waitFor();
  assert.equal(await page.locator('[data-preset-id="shiny-acoustic"]').count(),0);
  await page.locator('.instrument-preset summary').first().click();
  assert.ok((await page.locator('.instrument-preset dl').innerText()).includes('shinyguitar'));
  await page.screenshot({path:path.join(output,'instrument-directory.png'),fullPage:true});
  await choose.click();
  const draft=page.getByRole('textbox',{name:'讨论问题'});
  await draft.waitFor();
  await page.waitForFunction(()=>document.querySelector('textarea[aria-label="讨论问题"]')?.value.includes('instrument_id=electric-guitar'));
  assert.ok((await draft.inputValue()).includes('instrument_id=electric-guitar'));
  assert.ok(!(await draft.inputValue()).includes('preset_id='));
  assert.equal(await page.getByRole('button',{name:'允许改编模式'}).count(),0);assert.equal(await page.locator('input[aria-label="允许整轨插件和自动化"]').count(),0);
  await page.locator('.track-select').nth(1).click();
  await page.getByRole('button',{name:'发送 ↗',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'乐器草稿绑定的版本或声部已改变'}).waitFor();
  assert.deepEqual(productionWrites,[]);
  await page.getByRole('tab',{name:'音色与效果',exact:true}).click();
  await page.getByLabel('选择乐器',{exact:true}).selectOption('synth-bass');
  await page.locator('.instrument-preset').first().waitFor();
  const firstIds=await page.locator('.instrument-preset').evaluateAll(nodes=>nodes.map(n=>n.dataset.presetId));
  assert.equal(firstIds.length,20);
  await page.getByRole('button',{name:'下一页',exact:true}).click();
  await page.waitForFunction(first=>{const n=document.querySelector('.instrument-preset');return n&&n.dataset.presetId!==first;},firstIds[0]);
  const secondIds=await page.locator('.instrument-preset').evaluateAll(nodes=>nodes.map(n=>n.dataset.presetId));
  assert.equal(secondIds.filter(id=>firstIds.includes(id)).length,0);
  await page.getByLabel('选择乐器',{exact:true}).selectOption('unclassified');
  await page.getByRole('status').filter({hasText:'乐器身份待核对'}).waitFor();
  assert.ok(await choose.isDisabled());
  await page.getByLabel('选择乐器',{exact:true}).selectOption('electric-piano');
  await page.locator('[data-preset-id="rhodes-mark1"]').waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(output,'instrument-directory-mobile.png'),fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.getByRole('button',{name:'使用此音色 ↗',exact:true}).click();
  await draft.waitFor();
  await page.waitForFunction(()=>document.querySelector('textarea[aria-label="讨论问题"]')?.value.includes('preset_id=rhodes-mark1'));
  assert.ok((await draft.inputValue()).includes('preset_id=rhodes-mark1'));
  assert.deepEqual(productionWrites,[]);assert.deepEqual(errors,[]);
  await writeFile(path.join(output,'summary.json'),JSON.stringify({status:'succeeded',model_calls:0,production_writes:productionWrites,page_errors:errors,mobile_overflow:false,instrument_choice:true,optional_preset_choice:true,source_readback:true,stale_track_blocked:true,pagination_disjoint:true,unclassified_not_selectable:true},null,2));
  console.log(JSON.stringify({status:'succeeded',model_calls:0,production_writes:0}));
}finally{await browser.close();}
