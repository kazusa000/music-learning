// Exercise actual arranged versions, hybrid audio and historical citations without new model calls.
import {chromium} from 'playwright';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const [tokenFile,summaryFile,output]=process.argv.slice(2);
if(!output||output.startsWith('\\\\'))throw new Error('New local output required');
await mkdir(output,{recursive:false});
const summary=JSON.parse(await readFile(summaryFile,'utf8')),projectId=summary.project_id;
assert.equal(summary.status,'succeeded');
const token=(await readFile(tokenFile,'ascii')).trim();
const browser=await chromium.launch({headless:true});
const errors=[];
try{
 const page=await browser.newPage({viewport:{width:1600,height:1120}});
 page.on('pageerror',e=>errors.push(String(e)));
 await page.addInitScript(()=>{const Original=window.AudioContext;window.__starts=[];window.__contexts=[];
  window.AudioContext=class extends Original{constructor(...args){super(...args);window.__contexts.push(this);}createBufferSource(){const s=super.createBufferSource(),start=s.start.bind(s);s.start=(when=0,offset=0,...rest)=>{window.__starts.push({when,offset,duration:s.buffer?.duration,contextIndex:window.__contexts.indexOf(this)});return start(when,offset,...rest);};return s;}};
 });
 await page.goto(`http://127.0.0.1:8765/?project=${projectId}&view=workbench#token=${token}`);
 const studio=page.getByRole('region',{name:'音乐工作台'});await studio.waitFor();
 const api=async(operation,args={},expected)=>{const r=await page.request.post('http://127.0.0.1:8765/v1/commands',{data:{operation,arguments:args,expected_revision:expected??null,idempotency_key:expected?crypto.randomUUID():null}});const d=await r.json();assert.ok(d.ok,JSON.stringify(d));return d.result;};
 const revision=await api('revisions.get',{project_id:projectId}),rate=revision.snapshot.sample_rate;
 assert.equal(revision.id,summary.final_revision);
 await page.locator('[data-arrangement-revision="'+revision.id+'"]').waitFor();
 await api('audition.set',{project_id:projectId,state:{revision_id:revision.id,mode:'hybrid',hybrid_job_id:summary.hybrid_job_id,position_sample:60*rate,loop:false,loop_start_sample:60*rate,loop_end_sample:90*rate,playing:false}},revision.id);
 await page.waitForFunction(()=>Math.abs(Number(document.querySelector('.studio')?.dataset.position)-60)<.001);
 await page.getByRole('button',{name:'播放',exact:true}).click();
 await page.waitForFunction(()=>window.__starts.length>=1,null,{timeout:90000});
 await page.waitForTimeout(350);
 const first=await page.evaluate(()=>window.__starts[0]);assert.equal(first.duration,305);
 const startPosition=Number(await studio.getAttribute('data-position'));assert.ok(startPosition>60);
 await page.getByRole('button',{name:'原曲',exact:true}).click();
 await page.waitForFunction(()=>window.__starts.length>=2,null,{timeout:90000});
 await page.getByRole('button',{name:'版本',exact:true}).click();
 const baseline=page.locator('.version-card').filter({has:page.locator('code').filter({hasText:summary.baseline_revision.slice(0,8)})});
 await baseline.getByRole('button',{name:'设为 A'}).click();
 await page.waitForFunction(()=>window.__starts.length>=3,null,{timeout:90000});
 await page.getByRole('button',{name:/^重建/}).click();
 await page.waitForFunction(()=>window.__starts.length>=4,null,{timeout:90000});
 await page.waitForTimeout(350);
 const clock=await page.evaluate(()=>{const item=window.__starts.at(-1),context=window.__contexts[item.contextIndex],s=context.getOutputTimestamp();
  const now=s.contextTime&&s.performanceTime?s.contextTime+Math.max(0,performance.now()-s.performanceTime)/1000:context.currentTime-context.baseLatency-(context.outputLatency??0);
  const expected=item.offset+Math.max(0,now-item.when),actual=Number(document.querySelector('.studio').dataset.position);return{actual,expected,error:Math.abs(actual-expected),starts:window.__starts};});
 assert.ok(clock.actual>startPosition&&clock.error<.05,JSON.stringify(clock));
 assert.equal(clock.starts.at(-1).duration,307);
 await page.getByRole('button',{name:'暂停',exact:true}).click();
 await page.getByRole('button',{name:'讨论',exact:true}).click();
 const turns=await api('dialogue.list',{project_id:projectId,limit:1000}),firstTurn=turns.find(t=>t.id===summary.steps[0].turn_id),lastTurn=turns.find(t=>t.id===summary.steps.at(-1).turn_id);
 const historical=firstTurn.citations.find(c=>c.revision_id===summary.baseline_revision);assert.ok(historical);
 const firstArticle=page.locator('[data-turn="'+firstTurn.id+'"]');
 await firstArticle.locator('.citation-list button').filter({hasText:historical.label}).first().click();
 await page.waitForFunction(id=>document.querySelector('.studio')?.dataset.revision===id,historical.revision_id);
 await page.waitForFunction(seconds=>Math.abs(Number(document.querySelector('.studio')?.dataset.position)-seconds)<.001,historical.start_sample/rate);
 await page.getByRole('button',{name:'版本',exact:true}).click();
 await page.getByLabel('工程版本',{exact:true}).selectOption('head');
 await page.waitForFunction(id=>document.querySelector('.studio')?.dataset.revision===id,revision.id);
 await page.getByRole('button',{name:'讨论',exact:true}).click();
 await page.locator('[data-turn="'+lastTurn.id+'"]').getByRole('button',{name:'保存为研究笔记'}).click();
 await page.locator('.discussion-note').waitFor();
 const messages=await api('conversations.list',{project_id:projectId,limit:1000}),note=messages.find(n=>n.context?.source_turn_id===lastTurn.id);
 assert.ok(note);assert.equal(note.revision_id,revision.id);
 await page.getByRole('button',{name:/^讨论 /}).click();
 await page.waitForFunction(()=>Number(document.querySelector('.piano-roll')?.dataset.waveformBuckets)>0);
 await page.screenshot({path:path.join(output,'workbench.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth);assert.ok(overflow<=1,String(overflow));
 await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true});assert.deepEqual(errors,[]);
 await writeFile(path.join(output,'summary.json'),JSON.stringify({status:'succeeded',hybrid:true,version_ab:true,clock,historical_citation:true,note_revision:note.revision_id,overflow,page_errors:errors},null,2));
 console.log(JSON.stringify({status:'succeeded',clock_error:clock.error,historical_citation:true,overflow}));
}finally{await browser.close();}
