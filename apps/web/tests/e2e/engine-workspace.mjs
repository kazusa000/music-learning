import {chromium} from 'playwright';
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=path.resolve(process.argv[2]),fixture=JSON.parse(await readFile(path.join(root,'fixture.json'),'utf8'));
const base='http://127.0.0.1:'+fixture.port,token=fixture.token,project=fixture.project.id;
const report={checks:[],errors:[],audioRequests:[],pcmRequests:[],legacyPlanRequests:[]};
async function call(operation,args={},revision){const response=await fetch(base+'/v1/commands',{method:'POST',headers:{Authorization:'Bearer '+token,'Content-Type':'application/json'},body:JSON.stringify({operation,arguments:args,expected_revision:revision??null,idempotency_key:crypto.randomUUID().replaceAll('-','')})});const result=await response.json();assert(result.ok,JSON.stringify(result.error));return result.result;}
async function until(check,message,timeout=15000){const end=Date.now()+timeout;while(Date.now()<end){const value=await check();if(value)return value;await new Promise(resolve=>setTimeout(resolve,50));}throw Error(message);}
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:1536,height:864},deviceScaleFactor:2.5}),page=await context.newPage();
page.setDefaultTimeout(12000);
page.on('pageerror',e=>report.errors.push(e.message));
page.on('response',r=>{if((r.headers()['content-type']??'').startsWith('audio/'))report.audioRequests.push(r.url());});
page.on('request',r=>{if((r.postData()??'').includes('playback.live.'))report.pcmRequests.push(r.postData());if((r.postData()??'').includes('playback.get'))report.legacyPlanRequests.push(r.postData());});
try{
 await page.goto(base+'/?project='+project+'&view=workbench#token='+token);
 await page.locator('.studio').waitFor();
 await until(async()=>{const state=await call('engine.status');return state.applied_revision===fixture.revision.id&&state.status==='ready';},'Native graph did not become ready');
 assert.equal(await page.locator('.studio').getAttribute('data-audio-clock'),'native');
 await page.getByRole('button',{name:'播放',exact:true}).click();
 await until(async()=>{const s=await call('engine.status');return s.playing&&s.position_sample>4410&&s.meters[fixture.tracks[1]]>0;},'Device did not play');
 report.checks.push('4K workspace native playback');
 await page.getByLabel('音轨音量数值 1',{exact:true}).fill('-80');
 await page.getByLabel('音轨音量数值 1',{exact:true}).press('Tab');
 await until(async()=>(await call('engine.status')).monitor[fixture.tracks[0]].gain_db===-80,'Fader did not apply');
 await page.getByLabel('试听静音 1',{exact:true}).click();
 await until(async()=>(await call('engine.status')).meters[fixture.tracks[0]]===0,'Mute did not silence');
 await page.getByLabel('独奏 2',{exact:true}).click();
 await until(async()=>(await call('engine.status')).monitor[fixture.tracks[1]].solo,'Solo did not apply');
 let state=await call('engine.status');assert(state.monitor[fixture.tracks[1]].solo);
 await page.getByLabel('独奏 2',{exact:true}).click();
 await page.getByLabel('试听静音 1',{exact:true}).click();
 await until(async()=>!(await call('engine.status')).monitor[fixture.tracks[1]].solo,'Solo did not restore');
 report.checks.push('Fader, manual mute, solo exclusion and restore during playback');
 const before=await call('engine.status');
 await page.evaluate(()=>{const until=performance.now()+650;while(performance.now()<until){Math.sqrt(Math.random());}});
 state=await call('engine.status');assert(state.consumed_device_frames-before.consumed_device_frames>=24000);assert.equal(state.underruns,0);
 report.checks.push('650ms blocked browser does not interrupt device clock');
 let revision=await call('revisions.get',{project_id:project});
 await call('audition.set',{project_id:project,state:{revision_id:revision.id,mode:'mix',position_sample:441000,playing:true}},revision.id);
 await until(async()=>+await page.locator('.studio').getAttribute('data-position')>=10,'SDK seek did not reach UI');
 report.checks.push('SDK transport intent applies on shared native owner');
 const switchState=await call('engine.status'),switchPosition=switchState.position_sample;
 await page.locator('.mode-switch').getByRole('button',{name:'原曲',exact:true}).click();
 await until(async()=>{const s=await call('engine.status');return s.view==='original'&&s.playing&&s.position_sample>=switchPosition-4410;},'Original switch lost transport');
 assert.equal(await page.locator('.track-card').count(),3);assert(await page.getByLabel('独奏 2',{exact:true}).isDisabled());
 await page.getByLabel('独奏 1',{exact:true}).click();
 const reference=revision.snapshot.source_reference;
 await until(async()=>(await call('engine.status')).meters[reference.tracks[2].id]===0,'Original solo did not silence accompaniment');
 await page.screenshot({path:path.join(root,'original-4k.png')});
 await page.locator('.mode-switch').getByRole('button',{name:/重建/}).click();
 await until(async()=>{const s=await call('engine.status');return s.view==='arrangement'&&s.status==='ready'&&s.playing;},'Reconstruction did not resume');
 for(const [id,plugin] of Object.entries(switchState.plugins))assert.equal((await call('engine.status')).plugins[id].pid,plugin.pid,'A/B switch restarted a warm plugin');
 report.checks.push('Original/reconstruction switch, two audio tracks and silent melody');
 const original=await call('engine.status'),note={...revision.snapshot.notes[0],end_sample:44100};
 revision=await call('edits.apply',{project_id:project,scope:{track_ids:[fixture.tracks[0]],start_sample:0,end_sample:44100*32},operations:[{op:'put',collection:'notes',entity:note}],description:'Native UI fixture edit'},revision.id);
 await until(async()=>{const s=await call('engine.status');return s.applied_revision===revision.id&&s.meters[fixture.tracks[0]]===0&&s.meters[fixture.tracks[1]]>0;},'Committed note edit did not change audible track');
 state=await call('engine.status');assert.equal(state.plugins[fixture.tracks[1]].pid,original.plugins[fixture.tracks[1]].pid);
 await until(async()=>await page.locator('.studio').getAttribute('data-revision')===revision.id,'UI did not follow committed revision');
 assert((await call('engine.status')).playing,'Revision refresh stopped live playback');
 report.checks.push('Committed note edit updates actual sound, keeps unrelated worker');
 await page.screenshot({path:path.join(root,'arrangement-4k.png')});
 await page.getByRole('button',{name:'暂停',exact:true}).click();
 await until(async()=>!(await call('engine.status')).playing,'Pause failed');
 await page.locator('.studio-song-title').click();await page.keyboard.press('Space');
 await until(async()=>(await call('engine.status')).playing,'Space did not resume');
 await page.keyboard.press('Space');
 await until(async()=>!(await call('engine.status')).playing,'Space did not pause');
 report.checks.push('Pause/resume and Space keyboard control');
 await page.getByRole('button',{name:'返回音乐库',exact:true}).click();
 await page.getByRole('button',{name:'播放原曲试听',exact:true}).click();
 await until(async()=>{const s=await call('engine.status');return s.playing&&s.view==='original';},'Homepage did not use native source playback');
 await page.getByRole('button',{name:'暂停原曲试听',exact:true}).waitFor();
 await page.locator('h2').first().click();await page.keyboard.press('Space');
 await until(async()=>!(await call('engine.status')).playing,'Homepage Space did not pause');
 await page.screenshot({path:path.join(root,'home-4k.png')});
 report.checks.push('Homepage preview shares native output, stale workspace cleanup is harmless');
 assert.equal((await call('jobs.list',{project_id:project})).length,0);
 assert.equal(report.audioRequests.length,0);assert.equal(report.pcmRequests.length,0);assert.equal(report.legacyPlanRequests.length,0);assert.deepEqual(report.errors,[]);
 report.state=await call('engine.status');report.status='succeeded';
}catch(error){report.status='failed';report.failure=String(error.stack??error);await page.screenshot({path:path.join(root,'failure.png')}).catch(()=>{});throw error;}
finally{await writeFile(path.join(root,'browser-report.json'),JSON.stringify(report,null,2));await browser.close();await call('engine.close').catch(()=>{});}
console.log(JSON.stringify({status:report.status,checks:report.checks.length,audioRequests:report.audioRequests.length,pcmRequests:report.pcmRequests.length}));
