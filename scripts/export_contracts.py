"""Generate committed JSON Schema and TS types from the Python authority."""

import argparse
import json
from pathlib import Path
import sys
from pydantic import TypeAdapter

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from music_learning import contracts as c  # noqa: E402 - runnable without an editable install


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(x) for x in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts(x) for x in schema["anyOf"])
    if "oneOf" in schema:
        return " | ".join(ts(x) for x in schema["oneOf"])
    kind = schema.get("type")
    if kind == "array":
        return "Array<" + ts(schema["items"]) + ">"
    if kind == "object":
        if "properties" not in schema:
            additional = schema.get("additionalProperties", {})
            return "Record<string, " + (ts(additional) if isinstance(additional, dict) else "unknown") + ">"
        required = schema.get("required", [])
        return (
            "{ "
            + "; ".join(
                json.dumps(k) + ("" if k in required else "?") + ": " + ts(v)
                for k, v in schema["properties"].items()
            )
            + " }"
        )
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def generate():
    models = [
        c.Project,
        c.Asset,
        c.AnalysisRun,
        c.Snapshot,
        c.Revision,
        c.Job,
        c.Conversation,
        c.Request,
        *[model for model, _ in c.OPERATIONS.values()],
        *[
            model
            for model in c.RESULT_TYPES.values()
            if isinstance(model, type) and issubclass(model, c.Model)
        ],
    ]
    definitions = {}
    for model in models:
        schema = model.model_json_schema()
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    results = {}
    for operation, result_type in c.RESULT_TYPES.items():
        schema = TypeAdapter(result_type).json_schema()
        definitions.update(schema.pop("$defs", {}))
        results[operation] = schema
    definitions["UploadResult"] = c.UploadResult.model_json_schema()
    document = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "schema_version": 1,
        "$defs": dict(sorted(definitions.items())),
        "operations": {
            name: {"arguments": model.__name__, "result": results[name], "mutates": write}
            for name, (model, write) in c.OPERATIONS.items()
        },
    }
    types = "// Generated by scripts/export_contracts.py. Do not edit.\n"
    types += "\n".join(
        "export type " + name + " = " + ts(schema) + ";" for name, schema in sorted(definitions.items())
    )
    types += "\nexport type Operation = " + " | ".join(json.dumps(op) for op in c.OPERATIONS) + ";\n"
    types += (
        "export type OperationResults = { "
        + "; ".join(json.dumps(op) + ": " + ts(result) for op, result in results.items())
        + " };\n"
    )
    return {"schema.json": json.dumps(document, ensure_ascii=False, indent=2) + "\n", "types.ts": types}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    destination = ROOT / "packages/contracts"
    destination.mkdir(exist_ok=True, parents=True)
    for name, contents in generate().items():
        path = destination / name
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != contents:
                raise SystemExit("Contract drift: " + str(path))
        else:
            path.write_text(contents, encoding="utf-8", newline="\n")
