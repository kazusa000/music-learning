def apply(data):
    for line in ENTRIES.strip().splitlines():
        key, intro, *sections = line.split("|")
        for item in data["items"]:
            names = [item["id"], item["english"], *item.get("aliases", [])]
            if not any(name.casefold() == key.casefold() for name in names):
                continue
            item["intro"] = intro
            for name, text in zip(("rhythm", "harmony", "palette", "production"), sections):
                if not text:
                    continue
                others = [n for n in item["sections"][name] if n["label"] != "编曲切入"]
                item["sections"][name] = [{"label": "编曲切入", "text": text}, *others]
    data["editorial_version"] = 1
    return data


