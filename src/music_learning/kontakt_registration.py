"""Portable-profile library metadata, copied from original vendor NICNT records.

NICNT uses ProductHints/Product; the runtime library lookup reads
LibraryHints/Library. These are distinct containers. No activation records,
product identifiers, or vendor metadata values are generated by this module.
"""
from __future__ import annotations

from copy import deepcopy
from dataclasses import dataclass
import hashlib
import re
import xml.etree.ElementTree as ET

MAX_NICNT_BYTES = 8 * 1024**2


@dataclass(frozen=True)
class LibraryMetadata:
    reg_key: str
    name: str
    snpid: str
    source_sha256: str
    product_xml: bytes


def parse_nicnt(raw: bytes) -> LibraryMetadata:
    """Extract the existing public ProductHints XML without changing its fields."""
    if not isinstance(raw, bytes) or not 0 < len(raw) <= MAX_NICNT_BYTES:
        raise ValueError("NICNT metadata is missing or exceeds its size bound")
    start, finish = raw.find(b"<ProductHints"), raw.find(b"</ProductHints>")
    if start < 0 or finish < start:
        raise ValueError("NICNT does not contain a complete ProductHints record")
    xml = raw[start:finish + len(b"</ProductHints>")]
    if b"<!DOCTYPE" in xml.upper() or b"<!ENTITY" in xml.upper():
        raise ValueError("NICNT external XML declarations are unsupported")
    try:
        hints = ET.fromstring(xml)
    except ET.ParseError as error:
        raise ValueError("NICNT ProductHints XML is invalid") from error
    products = hints.findall("Product")
    if len(products) != 1:
        raise ValueError("NICNT must identify exactly one original product")
    product = products[0]
    values = {}
    for key in ("RegKey", "Name", "SNPID"):
        nodes = product.findall(key)
        if len(nodes) != 1 or not nodes[0].text or any(c in nodes[0].text for c in "\r\n\x00[]"):
            raise ValueError("NICNT has invalid or ambiguous " + key)
        values[key] = nodes[0].text
    return LibraryMetadata(values["RegKey"], values["Name"], values["SNPID"],
                           hashlib.sha256(raw).hexdigest(), ET.tostring(product, encoding="utf-8"))


def library_hints(existing: bytes | None, products: list[LibraryMetadata]) -> bytes:
    """Merge original metadata into the runtime container, preserving other libraries."""
    if existing:
        if len(existing) > MAX_NICNT_BYTES or b"<!DOCTYPE" in existing.upper() or b"<!ENTITY" in existing.upper():
            raise ValueError("Existing LibraryHints exceeds bounds or uses unsupported XML")
        try:
            root = ET.fromstring(existing)
        except ET.ParseError as error:
            raise ValueError("Existing LibraryHints is invalid") from error
        if root.tag != "LibraryHints":
            raise ValueError("Existing runtime hints must use LibraryHints/Library")
    else:
        root = ET.Element("LibraryHints")
    incoming = {}
    for metadata in products:
        if metadata.reg_key.casefold() in incoming:
            raise ValueError("Duplicate library registration key")
        incoming[metadata.reg_key.casefold()] = metadata
    all_keys, all_ids = {}, {}
    for child in list(root):
        if child.tag != "Library":
            continue
        key = child.findtext("RegKey")
        identity = child.findtext("SNPID")
        if not key or not identity:
            raise ValueError("Existing runtime library lacks its original RegKey/SNPID")
        folded = key.casefold()
        if folded in all_keys:
            raise ValueError("Existing runtime hints have duplicate library keys")
        all_keys[folded] = child
        if folded not in incoming:
            if identity.casefold() in all_ids:
                raise ValueError("Existing library identifiers collide")
            all_ids[identity.casefold()] = folded
    for key, metadata in incoming.items():
        old = all_keys.get(key)
        if old is not None:
            if old.findtext("SNPID") != metadata.snpid:
                raise ValueError("Cannot replace an existing library's original identifier")
            root.remove(old)
        if metadata.snpid.casefold() in all_ids:
            raise ValueError("Library identifiers collide; never synthesize a replacement")
        all_ids[metadata.snpid.casefold()] = key
        product = ET.fromstring(metadata.product_xml)
        library = ET.SubElement(root, "Library", product.attrib)
        for element in product:
            library.append(deepcopy(element))
    return ET.tostring(root, encoding="utf-8", xml_declaration=True)


def profile_settings(existing: str, records: list[tuple[LibraryMetadata, str, str | None]]) -> str:
    """Update only selected library sections in an independent Settings.cfg.

    All NICNT fields are copied unchanged. ContentDir/version describe the
    installation, not activation. The caller owns profile locking/atomic writes.
    """
    if not isinstance(existing, str) or "\x00" in existing:
        raise ValueError("Settings.cfg must be decoded text")
    header = re.compile(r"(?m)^\[([^\r\n]+)\][ \t]*\r?$")
    result = existing
    seen = set()
    for metadata, content_dir, version in records:
        folded = metadata.reg_key.casefold()
        if folded in seen:
            raise ValueError("Duplicate library settings update")
        seen.add(folded)
        if not content_dir or any(c in content_dir for c in "\r\n\x00") or (
            version is not None and (not version or any(c in version for c in "\r\n\x00"))
        ):
            raise ValueError("Invalid library installation path/version")
        product = ET.fromstring(metadata.product_xml)
        fields = {"Name": metadata.name, "SNPID": metadata.snpid, "ContentDir": content_dir}
        if version is not None:
            fields["ContentVersion"] = version
        company = product.findtext("Company")
        if company:
            fields["Company"] = company
        specific = product.find("ProductSpecific")
        if specific is not None:
            for key in ("HU", "JDX"):
                value = specific.findtext(key)
                if value:
                    fields[key] = value
        for value in fields.values():
            if any(c in value for c in "\r\n\x00"):
                raise ValueError("Original vendor metadata cannot be represented as a settings value")
        matches = list(header.finditer(result))
        selected = [(index, match) for index, match in enumerate(matches)
                    if match[1].casefold() == folded]
        if len(selected) > 1:
            raise ValueError("Settings.cfg has ambiguous duplicate library sections")
        if selected:
            index, match = selected[0]
            end = matches[index + 1].start() if index + 1 < len(matches) else len(result)
            original_section = result[match.end():end]
            # Keep unknown fields, replacing only metadata managed here.
            kept = [line for line in original_section.splitlines()
                    if not any(line.casefold().startswith(key.casefold() + "=") for key in fields)]
            section = result[match.start():match.end()].rstrip("\r\n") + "\n"
            section += "\n".join(line for line in kept if line.strip())
            if not section.endswith("\n"):
                section += "\n"
            section += "".join(key + "=sz:" + value + "\n" for key, value in fields.items()) + "\n"
            result = result[:match.start()] + section + result[end:]
        else:
            result = result.rstrip("\r\n") + "\n\n[" + metadata.reg_key + "]\n"
            result += "".join(key + "=sz:" + value + "\n" for key, value in fields.items())
    return result
